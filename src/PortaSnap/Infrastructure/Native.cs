    [StructLayout(LayoutKind.Sequential)]
    public struct INPUT
    {
        public uint type;
        public MOUSEINPUT mi;
    }

    // MOUSEINPUT is the largest member of the INPUT union on x64 together with KEYBDINPUT padding, so this layout is valid for mouse input.
